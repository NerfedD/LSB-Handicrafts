-- Confirmed entries, never inferred from placing/receiving an order.
-- Historical paid_at values are retained but are not evidence of payment.
drop trigger if exists raw_material_orders_payment on public.raw_material_orders;
alter table public.raw_material_orders alter column order_date set default private.shop_today();

create table if not exists public.supplier_payments (
  id bigint generated by default as identity primary key,
  order_id bigint references public.raw_material_orders(id) on delete restrict,
  kind text not null check (kind in ('payment','refund','card_settlement')),
  amount numeric(16,2) not null check (amount > 0 and amount <= 100000000000),
  method text not null check (method in ('cash','gcash','bank','check','card')),
  occurred_on date not null,
  reference text check (char_length(reference) <= 80),
  note text check (char_length(note) <= 500),
  reduces_bill boolean not null default false,
  recorded_by bigint not null references public.staff(id),
  created_at timestamptz not null default now(),
  request_id uuid not null unique,
  request_payload jsonb not null,
  check ((kind = 'card_settlement' and order_id is null and method <> 'card')
      or (kind in ('payment','refund') and order_id is not null)),
  check (not reduces_bill or kind = 'refund'),
  check (method = 'cash' or length(btrim(reference)) > 0)
);
create index if not exists supplier_payments_order_idx on public.supplier_payments(order_id);
create index if not exists supplier_payments_date_idx on public.supplier_payments(occurred_on);
alter table public.supplier_payments enable row level security;
revoke all on public.supplier_payments from public, anon, authenticated;
grant select on public.supplier_payments to authenticated;
drop policy if exists "Managers read supplier payments" on public.supplier_payments;
create policy "Managers read supplier payments" on public.supplier_payments for select
  to authenticated using ((select private.is_manager_or_admin()));

create or replace function private.supplier_balance(p_order_id bigint)
returns jsonb language sql stable set search_path = '' as $fn$
  with totals as (
    select coalesce(sum(amount) filter(where kind='payment'),0) as paid,
      coalesce(sum(amount) filter(where kind='refund'),0) as refunded,
      coalesce(sum(amount) filter(where kind='refund' and reduces_bill),0) as credit
    from public.supplier_payments where order_id=p_order_id
  ) select jsonb_build_object('paid',t.paid,'refunded',t.refunded,'credit',t.credit,
      'outstanding',case when o.status='Cancelled' then 0 else greatest(0,o.total_cost-t.credit-t.paid+t.refunded) end,
      'refund_due',case when o.status='Cancelled' then greatest(0,t.paid-t.refunded) else 0 end)
    from public.raw_material_orders o cross join totals t where o.id=p_order_id;
$fn$;
revoke all on function private.supplier_balance(bigint) from public, anon, authenticated;

create or replace function public.supplier_payment_account(p_order_id bigint)
returns jsonb language plpgsql stable security definer set search_path = '' as $fn$
declare result jsonb;
begin
  if (select auth.uid()) is null or not coalesce(private.is_manager_or_admin(),false) then
    raise exception 'Only a manager or administrator can read supplier payments.';
  end if;
  result := private.supplier_balance(p_order_id);
  if result is null then raise exception 'That supplier order no longer exists.'; end if;
  return result;
end;
$fn$;
revoke all on function public.supplier_payment_account(bigint) from public, anon;
grant execute on function public.supplier_payment_account(bigint) to authenticated;

create or replace function public.record_supplier_payment(p_order_id bigint, p_data jsonb, p_request_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $fn$
declare
  actor public.staff; ord public.raw_material_orders; saved public.supplier_payments;
  n numeric; method text; kind text; ref text; note text; day date; credit boolean;
  account jsonb; room numeric; card_room numeric;
begin
  if (select auth.uid()) is null or not coalesce(private.is_manager_or_admin(),false) then
    raise exception 'Only a manager or administrator can record supplier payments.';
  end if;
  select * into actor from public.staff where lower(email)=lower((select auth.jwt())->>'email') and status='Active';
  if p_request_id is null or jsonb_typeof(p_data) is distinct from 'object' then raise exception 'A payment request and request ID are required.'; end if;
  -- Serialise writes to the shared card balance, and retry checks, before locking an order.
  perform pg_catalog.pg_advisory_xact_lock(64198,1);
  select * into saved from public.supplier_payments where request_id=p_request_id;
  if found then
    if saved.order_id is distinct from p_order_id or saved.request_payload is distinct from p_data or saved.recorded_by<>actor.id then
      raise exception 'This request ID was already used for a different entry.';
    end if;
    return jsonb_build_object('entry',to_jsonb(saved),'replayed',true);
  end if;
  n := (p_data->>'amount')::numeric; method := p_data->>'method'; kind := p_data->>'kind';
  ref := nullif(btrim(p_data->>'reference'),''); note := nullif(btrim(p_data->>'note'),'');
  day := (p_data->>'occurred_on')::date; credit := coalesce((p_data->>'reduces_bill')::boolean,false);
  if n is null or n<=0 or n>100000000000 then raise exception 'Enter a positive amount up to 100,000,000,000.'; end if;
  if n<>round(n,2) then raise exception 'Use at most two decimal places.'; end if;
  if kind is null or kind not in ('payment','refund','card_settlement') then raise exception 'Choose payment, refund or card-bill payment.'; end if;
  if method is null or method not in ('cash','gcash','bank','check','card') then raise exception 'Choose a payment method.'; end if;
  if method<>'cash' and ref is null then raise exception 'Enter the receipt or transaction reference.'; end if;
  if char_length(ref)>80 or char_length(note)>500 then raise exception 'Keep the reference to 80 and the note to 500 characters.'; end if;
  if day is null or day>private.shop_today() then raise exception 'Choose the payment date, no later than today.'; end if;
  if kind='refund' and note is null then raise exception 'Explain why the supplier refunded this amount.'; end if;
  if credit and kind<>'refund' then raise exception 'Only a refund can reduce the supplier bill.'; end if;
  if kind='card_settlement' then
    if p_order_id is not null or method='card' then raise exception 'A card-bill payment must use cash, bank, GCash or check and has no supplier order.'; end if;
    select coalesce(sum(case when p.kind='payment' and p.method='card' then p.amount
      when p.kind='refund' and p.method='card' then -p.amount when p.kind='card_settlement' then -p.amount else 0 end),0)
      into room from public.supplier_payments p;
    if n>room then raise exception 'That is more than the recorded card balance owed.'; end if;
  else
    select * into ord from public.raw_material_orders where id=p_order_id for update;
    if not found then raise exception 'That supplier order no longer exists.'; end if;
    account := private.supplier_balance(ord.id);
    if kind='payment' then
      if ord.status='Cancelled' then raise exception 'A cancelled order cannot receive another payment.'; end if;
      if n>(account->>'outstanding')::numeric then raise exception 'That is more than is owed on this supplier order.'; end if;
    else
      if n>(account->>'paid')::numeric-(account->>'refunded')::numeric then raise exception 'That is more than was paid and not yet refunded.'; end if;
      -- A card refund can only reverse card-funded payments on this order.
      select coalesce(sum(case when p.kind='payment' then p.amount else -p.amount end),0) into card_room
        from public.supplier_payments p where p.order_id=ord.id and p.method='card';
      if method='card' and n>card_room then
        raise exception 'The card refund exceeds the amount paid by card on this order.';
      end if;
    end if;
  end if;
  insert into public.supplier_payments(order_id,kind,amount,method,occurred_on,reference,note,reduces_bill,recorded_by,request_id,request_payload)
    values(p_order_id,kind,n,method,day,ref,note,credit,actor.id,p_request_id,p_data) returning * into saved;
  insert into public.activity_log(id,type,staff_name,description,subject,at)
    values(nextval('private.workshop_id_seq'),'stock',actor.name,
      format('Recorded supplier %s: ₱%s via %s on %s%s',kind,n,method,day,case when note is null then '' else ': '||note end),
      case when p_order_id is null then 'Card bill' else 'Supplier order #'||p_order_id end,now());
  return jsonb_build_object('entry',to_jsonb(saved),'replayed',false);
end;
$fn$;
revoke all on function public.record_supplier_payment(bigint,jsonb,uuid) from public, anon;
grant execute on function public.record_supplier_payment(bigint,jsonb,uuid) to authenticated;

-- Price corrections must not erase an amount already settled. Cancellation
-- preserves the ledger; the FK also prevents deleting an order with entries.
create or replace function private.guard_supplier_settled_total()
returns trigger language plpgsql security definer set search_path = '' as $fn$
declare settled numeric;
begin
  if new.quantity_ordered=old.quantity_ordered and new.unit_price=old.unit_price then return new; end if;
  select coalesce(sum(case when kind='payment' then amount when kind='refund' and not reduces_bill then -amount else 0 end),0)
    into settled from public.supplier_payments where order_id=old.id;
  if new.quantity_ordered::numeric*new.unit_price<settled then raise exception 'The bill cannot be reduced below its confirmed payments and credits.'; end if;
  return new;
end;
$fn$;
revoke all on function private.guard_supplier_settled_total() from public, anon, authenticated;
drop trigger if exists supplier_order_settled_total on public.raw_material_orders;
create trigger supplier_order_settled_total before update of quantity_ordered,unit_price on public.raw_material_orders
  for each row execute function private.guard_supplier_settled_total();

create or replace function public.cash_flow_summary(p_from date,p_to date)
returns jsonb language plpgsql stable security definer set search_path = '' as $fn$
declare collections numeric; customer_refunds numeric; payments numeric; refunds numeric; card_paid numeric;
  card_balance numeric; owed numeric; purchases numeric; undated integer;
begin
  if (select auth.uid()) is null or not coalesce(private.is_manager_or_admin(),false) then
    raise exception 'Only a manager or administrator can read cash flow.';
  end if;
  if p_from is null or p_to is null or p_from>p_to or p_to>private.shop_today() then raise exception 'Choose a valid date range ending no later than today.'; end if;
  select coalesce(sum(amount),0) into collections from public.order_payments where received_on between p_from and p_to;
  select coalesce(sum(case when e->>'handedBack' is not null then private.order_num(e->>'handedBack')
    when e->>'method'='credit' then 0 else private.order_num(e->>'amount') end),0) into customer_refunds
    from public.orders o cross join lateral jsonb_array_elements(o.refund_history) e
    where (nullif(e->>'refundedAt','')::timestamptz at time zone 'Asia/Manila')::date between p_from and p_to;
  select count(*)::integer into undated from public.orders o cross join lateral jsonb_array_elements(o.refund_history) e
    where nullif(e->>'refundedAt','') is null;
  select coalesce(sum(amount) filter(where kind='payment' and method<>'card'),0),
    coalesce(sum(amount) filter(where kind='refund' and method<>'card'),0),
    coalesce(sum(amount) filter(where kind='card_settlement'),0)
    into payments,refunds,card_paid from public.supplier_payments where occurred_on between p_from and p_to;
  select coalesce(sum(case when kind='payment' and method='card' then amount
    when kind='refund' and method='card' then -amount when kind='card_settlement' then -amount else 0 end),0)
    into card_balance from public.supplier_payments;
  select coalesce(sum(greatest(0,o.total_cost-coalesce(p.settled,0))),0) into owed
    from public.raw_material_orders o left join (
      select order_id,sum(case when kind='payment' then amount when kind='refund' and not reduces_bill then -amount else 0 end) as settled
      from public.supplier_payments group by order_id
    ) p on p.order_id=o.id where o.status<>'Cancelled';
  select coalesce(sum(total_cost),0) into purchases from public.raw_material_orders
    where status<>'Cancelled' and order_date between p_from and p_to;
  return jsonb_build_object('customer_collections',collections,'customer_refunds',customer_refunds,
    'supplier_payments',payments,'supplier_refunds',refunds,'card_settlements',card_paid,
    'net_cash',collections-customer_refunds-payments+refunds-card_paid,'card_balance',card_balance,
    'supplier_outstanding',owed,'purchases',purchases,'undated_refunds',undated);
end;
$fn$;
revoke all on function public.cash_flow_summary(date,date) from public, anon;
grant execute on function public.cash_flow_summary(date,date) to authenticated;
